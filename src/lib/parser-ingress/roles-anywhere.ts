/**
 * Signs and sends one AWS IAM Roles Anywhere `CreateSession` request using
 * the exact end-entity certificate/private key supplied. The private key
 * is imported for this single operation and never persisted or returned.
 */
export async function createRolesAnywhereSession(
  params: CreateSessionParams,
): Promise<RolesAnywhereSessionCredentials> {
  const host = `rolesanywhere.${params.region}.amazonaws.com`;
  const uri = "/sessions";
  const url = `https://${host}${uri}`;

  const body = JSON.stringify({
    durationSeconds: params.durationSeconds,
    profileArn: params.profileArn,
    roleArn: params.roleArn,
    trustAnchorArn: params.trustAnchorArn,
  });

  // instruction1.172.md / instruction1.186.md -- sanitized failure
  // categorization for the Roles Anywhere credential path. Every catch here
  // discards the original error entirely and throws a fixed, non-secret
  // category string only -- never certificate/key content, never a
  // provider body, never anything derived from the caught error itself.
  // The caller (parser-lease.ts) no longer extracts/logs these category
  // strings post-C5 (instruction1.186.md's repository cleanup removed that
  // consumer deliberately, conservatively, without touching this validated
  // signing implementation) -- they remain here only as an inert,
  // already-sanitized fail-closed boundary around each risky step.
  let certDer: Uint8Array;
  let chainDer: Uint8Array | null;
  let serialDecimal: string;
  try {
    certDer = pemToDer(params.certificatePem);
    chainDer =
      params.certificateChainPem.trim().length > 0 ? pemToDer(params.certificateChainPem) : null;
    serialDecimal = extractSerialNumberDecimal(certDer);
  } catch {
    throw new Error("certificate_parse_failed");
  }

  const now = new Date();
  const { amzDate, dateStamp } = amzDateStamp(now);
  const hashedPayload = await sha256Hex(body);

  const headers: Record<string, string> = {
    host,
    "x-amz-date": amzDate,
    "x-amz-x509": toBase64(certDer),
    "content-type": "application/json",
  };
  if (chainDer) headers["x-amz-x509-chain"] = toBase64(chainDer);

  const { canonicalRequest, signedHeaders } = buildCanonicalRequest(
    "POST",
    uri,
    headers,
    hashedPayload,
  );
  const hashedCanonicalRequest = await sha256Hex(canonicalRequest);
  const credentialScope = `${dateStamp}/${params.region}/${ROLES_ANYWHERE_SERVICE}/aws4_request`;
  const stringToSign = [ALGORITHM, amzDate, credentialScope, hashedCanonicalRequest].join("\n");

  let privateKey: CryptoKey;
  try {
    privateKey = await crypto.subtle.importKey(
      "pkcs8",
      pemToDer(params.privateKeyPem).slice().buffer as ArrayBuffer,
      { name: "RSASSA-PKCS1-v1_5", hash: "SHA-256" },
      false, // non-extractable
      ["sign"],
    );
  } catch {
    throw new Error("private_key_import_failed");
  }

  let signatureHex: string;
  try {
    const signatureBytes = new Uint8Array(
      await crypto.subtle.sign(
        "RSASSA-PKCS1-v1_5",
        privateKey,
        new TextEncoder().encode(stringToSign).slice().buffer as ArrayBuffer,
      ),
    );
    signatureHex = toHex(signatureBytes);
  } catch {
    throw new Error("signature_failed");
  }

  const authorizationHeader = `${ALGORITHM} Credential=${serialDecimal}/${credentialScope}, SignedHeaders=${signedHeaders}, Signature=${signatureHex}`;

  let response: Response;
  try {
    response = await fetch(url, {
      method: "POST",
      headers: { ...headers, authorization: authorizationHeader },
      body,
    });
  } catch {
    throw new Error("create_session_network_failed");
  }

  if (!response.ok) {
    // Never surface the raw provider body -- it may echo request detail.
    throw new Error(`create_session_http_failed:${response.status}`);
  }

  let payload: {
    credentialSet?: {
      credentials?: {
        accessKeyId: string;
        secretAccessKey: string;
        sessionToken: string;
        expiration: string;
      };
    }[];
  };
  try {
    payload = await response.json();
  } catch {
    throw new Error("create_session_malformed_response");
  }
  const credentials = payload.credentialSet?.[0]?.credentials;
  if (!credentials) {
    throw new Error("create_session_malformed_response");
  }
  return credentials;
}
